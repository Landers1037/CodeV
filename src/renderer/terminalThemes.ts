export function getTerminalTheme(scheme?: TerminalColorScheme): ITheme {
  return terminalColorSchemes[scheme ?? 'TokyoNight'] ?? terminalColorSchemes.TokyoNight;
}

export function getTerminalAnsiPalette(scheme?: TerminalColorScheme): string[] {
  const theme = getTerminalTheme(scheme);
  const palette = [
    theme.black,
    theme.red,
    theme.green,
    theme.yellow,
    theme.blue,
    theme.magenta,
    theme.cyan,
    theme.white,
    theme.brightBlack,
    theme.brightRed,
    theme.brightGreen,
    theme.brightYellow,
    theme.brightBlue,
    theme.brightMagenta,
    theme.brightCyan,
    theme.brightWhite,
  ].filter(Boolean) as string[];
  return palette;
}

